import type {
  GenerateContentParameters,
  GoogleGenAI,
} from "@google/genai";

const REQUEST_TIMEOUT_MS = 90 * 1000;

const FALLBACK_STATUS_CODES = [404, 408, 429, 500, 502, 503, 504];

type ModelRequest = Omit<GenerateContentParameters, "model">;

const getErrorMessage = (error: unknown) =>
  error instanceof Error ? error.message : String(error);

const canTryNextModel = (error: unknown) => {
  const status = (error as { status?: unknown } | null)?.status;

  return typeof status !== "number" || FALLBACK_STATUS_CODES.includes(status);
};

export const generateWithFallback = async <T>(
  gemini: GoogleGenAI,
  models: string[],
  request: ModelRequest,
  parse: (text: string) => T,
): Promise<T> => {
  let lastError: unknown;

  for (const model of models) {
    let text: string | undefined;

    try {
      const response = await gemini.models.generateContent({
        ...request,
        model,
        config: {
          ...request.config,
          httpOptions: { timeout: REQUEST_TIMEOUT_MS },
        },
      });
      text = response.text;
    } catch (error) {
      if (!canTryNextModel(error)) throw error;

      lastError = error;
      console.warn(`Gemini model ${model} failed:`, getErrorMessage(error));
      continue;
    }

    try {
      if (!text) {
        throw new Error("Gemini returned an empty response");
      }

      const result = parse(text);
      console.log(`Gemini response generated by ${model}`);
      return result;
    } catch (error) {
      lastError = error;
      console.warn(
        `Gemini model ${model} returned an invalid response:`,
        getErrorMessage(error),
      );
    }
  }

  throw new Error(
    `All Gemini models failed. Last error: ${getErrorMessage(lastError)}`,
  );
};